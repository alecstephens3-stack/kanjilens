// Combine all levels
const allKanji: KanjiData[] = [...N5, ...N4, ...N3, ...N2, ...N1];

// Build dictionary, deduplicating by kanji character
const dict: Record<string, KanjiEntry> = {};

for (const [char, meanings, onyomi, kunyomi, compounds] of allKanji) {
  if (dict[char]) continue; // skip duplicates
  dict[char] = {
    meanings,
    readings: { onyomi, kunyomi },
    compounds: compounds.map(([word, reading, meaning]) => ({ word, reading, meaning })),
  };
}

const outputPath = join(__dirname, "..", "src", "data", "kanji-dict.json");
writeFileSync(outputPath, JSON.stringify(dict, null, 2), "utf-8");

